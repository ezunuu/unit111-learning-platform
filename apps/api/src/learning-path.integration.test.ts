import test from 'node:test';
import assert from 'node:assert/strict';
import express, { type Request } from 'express';
import { once } from 'node:events';
import { eq, sql } from 'drizzle-orm';
import { db, pool } from './db.js';
import * as s from './schema.js';
import { learningRouter } from './learning.js';
import { courseManagementRouter } from './course-management.js';

test('learning read endpoints work against the isolated local test database without creating learner data', { skip: process.env.UNIT111_TEST_DATABASE_INTEGRATION !== '1' }, async (t) => {
  const databaseUrl = new URL(process.env.DATABASE_URL || '');
  assert.equal(databaseUrl.pathname.replace(/^\//, ''), 'unit111_admin_test');
  assert.ok(['localhost', '127.0.0.1', '::1'].includes(databaseUrl.hostname));
  const [{ databaseName }] = await db.select({ databaseName: sql<string>`current_database()` }).from(s.users).limit(1);
  assert.equal(databaseName, 'unit111_admin_test');
  const [admin] = await db.select({ id: s.users.id, role: s.users.role }).from(s.users).where(eq(s.users.role, 'admin')).limit(1);
  assert.ok(admin);
  const chapterBadge = await db.select({ id: s.achievements.id }).from(s.achievements).where(eq(s.achievements.code, 'chapter_complete')).limit(1);
  assert.equal(chapterBadge.length, 1, 'chapter completion achievement is seeded by migration');
  const app = express(); app.use(express.json());
  app.use((req: Request, _res, next) => { const requestedRole = req.header('x-test-role'); const role = requestedRole === 'employee' || requestedRole === 'training_manager' ? requestedRole : admin.role; req.user = { id: admin.id, username: 'integration-test', fullName: 'Integration Test', role, mustChangePassword: false }; next(); });
  app.use('/learning', learningRouter);
  app.use('/', courseManagementRouter);
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.close(); await once(server, 'close'); await pool.end(); });
  const address = server.address(); assert.ok(address && typeof address === 'object'); const base = `http://127.0.0.1:${address.port}/learning`;
  const pathResponse = await fetch(`${base}/path`); assert.equal(pathResponse.status, 200);
  const path = await pathResponse.json() as { items: unknown[]; courses: unknown[]; summary: { xp: number; totalLessons: number } };
  assert.deepEqual(path.items, []); assert.deepEqual(path.courses, []); assert.equal(path.summary.xp, 0); assert.equal(path.summary.totalLessons, 0);
  const queueResponse = await fetch(`${base}/review-queue`); assert.equal(queueResponse.status, 200);
  const queue = await queueResponse.json() as { items: unknown[] }; assert.deepEqual(queue.items, []);
  const startResponse = await fetch(`${base}/review-queue/start`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
  assert.equal(startResponse.status, 409);
  const start = await startResponse.json() as { error: { code: string } }; assert.equal(start.error.code, 'NO_REVIEW_QUESTIONS');
  const adminCourses = await fetch(`${base.replace('/learning', '')}/admin/courses`); assert.equal(adminCourses.status, 200);
  const learnerCourses = await fetch(`${base.replace('/learning', '')}/admin/courses`, { headers: { 'x-test-role': 'employee' } }); assert.equal(learnerCourses.status, 403);
  const managerReview = await fetch(`${base.replace('/learning', '')}/admin/content-blocks/00000000-0000-4000-8000-000000000001/review`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-test-role': 'training_manager' }, body: JSON.stringify({ reviewStatus: 'approved' }) }); assert.equal(managerReview.status, 403);
});
